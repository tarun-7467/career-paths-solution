-- Record each change to a job application's status.

BEGIN;

CREATE TABLE public.job_status_events (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    job_id integer NOT NULL REFERENCES public.job_applications(job_id) ON DELETE CASCADE,
    previous_status varchar NOT NULL,
    new_status varchar NOT NULL,
    changed_at timestamptz NOT NULL DEFAULT now(),
    source text,
    notes text
);

ALTER TABLE public.job_status_events ENABLE ROW LEVEL SECURITY;

CREATE INDEX job_status_events_job_changed_idx
    ON public.job_status_events (job_id, changed_at DESC);

COMMIT;